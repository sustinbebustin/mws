package ports

import (
	"bufio"
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/sustinbebustin/mws/internal/atomicfile"
	"github.com/sustinbebustin/mws/internal/config"
)

// LeaseFile is the Port lease's name at a working copy root, an mws marker.
const LeaseFile = config.MarkerPrefix + "ports.env"

const leaseHeader = "# Generated by mws (mws ports claim); do not edit. Port lease of this working copy.\n"

// LeaseError reports a lease file mws cannot read a slot from.
type LeaseError struct {
	// Path is the lease file.
	Path string
	// Reason says what is wrong with it.
	Reason string
}

func (e *LeaseError) Error() string {
	return fmt.Sprintf("port lease %s: %s; run `mws ports claim --slot N` to rewrite it, or delete it to put the copy on the default ports", e.Path, e.Reason)
}

// LeasePath is the lease file of the working copy at copyDir.
func LeasePath(copyDir string) string {
	return filepath.Join(copyDir, LeaseFile)
}

// ReadSlot returns the Port slot recorded in the lease of the working copy at
// copyDir: its MWS_SLOT line. A copy without a lease is on slot 0, the
// default ports. A lease without a valid slot of at least 1 is a
// *LeaseError.
func ReadSlot(copyDir string) (int, error) {
	path := LeasePath(copyDir)
	body, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return 0, nil
	}
	if err != nil {
		return 0, fmt.Errorf("read port lease %s: %w", path, err)
	}
	sc := bufio.NewScanner(bytes.NewReader(body))
	for sc.Scan() {
		value, ok := strings.CutPrefix(sc.Text(), config.VarSlot+"=")
		if !ok {
			continue
		}
		slot, err := strconv.Atoi(value)
		if err != nil || slot < 1 {
			return 0, &LeaseError{Path: path, Reason: fmt.Sprintf("%s is %q, want an integer of at least 1", config.VarSlot, value)}
		}
		return slot, nil
	}
	if err := sc.Err(); err != nil {
		return 0, fmt.Errorf("read port lease %s: %w", path, err)
	}
	return 0, &LeaseError{Path: path, Reason: "no " + config.VarSlot + " line"}
}

// WriteLease atomically writes the lease of the working copy at copyDir: a
// header line saying mws generated it, then one dotenv line per variable of
// e, in order. e.Slot must be at least 1; slot 0 is never leased, so a copy
// returns to the default ports through RemoveLease.
func WriteLease(copyDir string, e Exports) error {
	path := LeasePath(copyDir)
	if e.Slot < 1 {
		return fmt.Errorf("write port lease %s: slot %d is not leasable; slot 0 is the default ports, recorded by having no lease", path, e.Slot)
	}
	var b strings.Builder
	b.WriteString(leaseHeader)
	for _, line := range e.Dotenv() {
		b.WriteString(line)
		b.WriteString("\n")
	}
	if err := atomicfile.Write(path, []byte(b.String()), 0o644); err != nil {
		return fmt.Errorf("write port lease: %w", err)
	}
	return nil
}

// RemoveLease deletes the lease of the working copy at copyDir, putting it
// on the default ports. A copy without a lease is left as it is.
func RemoveLease(copyDir string) error {
	path := LeasePath(copyDir)
	if err := os.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("remove port lease %s: %w", path, err)
	}
	return nil
}

// dotenvQuote quotes value so direnv's dotenv, just and the shell all read
// it back verbatim: bare when every byte is inert, single quotes (no
// expansion) when possible, double quotes with escapes otherwise.
func dotenvQuote(value string) string {
	special := func(r rune) bool {
		return (r < 'a' || r > 'z') && (r < 'A' || r > 'Z') && (r < '0' || r > '9') && !strings.ContainsRune("_./:@%+,=-", r)
	}
	if strings.IndexFunc(value, special) < 0 {
		return value
	}
	if !strings.ContainsAny(value, "'\n") {
		return "'" + value + "'"
	}
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`, "`", "\\`", "\n", `\n`)
	return `"` + r.Replace(value) + `"`
}
