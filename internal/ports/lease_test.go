func mkdir(t *testing.T, dir string) {
	t.Helper()
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
}

func TestReadSlotWithoutLeaseIsDefault(t *testing.T) {
	slot, err := ReadSlot(t.TempDir())
	if err != nil || slot != 0 {
		t.Fatalf("ReadSlot = %d, %v; want 0, nil", slot, err)
	}
}

func TestLeaseRoundTrip(t *testing.T) {
	copyDir := t.TempDir()
	e := NewExports(loadConfig(t, shopConfig), "/work/my shop", "two", 3)
	if err := WriteLease(copyDir, e); err != nil {
		t.Fatalf("WriteLease: %v", err)
	}
	slot, err := ReadSlot(copyDir)
	if err != nil || slot != 3 {
		t.Fatalf("ReadSlot = %d, %v; want 3, nil", slot, err)
	}
	body, err := os.ReadFile(filepath.Join(copyDir, LeaseFile))
	if err != nil {
		t.Fatal(err)
	}
	want := "# Generated by mws (mws ports claim); do not edit. Port lease of this working copy.\n" +
		"MWS_SLOT=3\n" +
		"MWS_COPY=two\n" +
		"MWS_COPY_SLUG=two\n" +
		"MWS_META='/work/my shop'\n" +
		"MWS_PORT_WEB=5203\n" +
		"MWS_PORT_DB=5462\n" +
		"DB_HOST_PORT=5462\n" +
		"COMPOSE_PROJECT_NAME=shop-two\n" +
		"DATABASE_URL=postgres://localhost:5462/shop\n"
	if string(body) != want {
		t.Fatalf("lease =\n%s\nwant\n%s", body, want)
	}
}

func TestLeaseQuotesValuesDotenvWouldSplitOrExpand(t *testing.T) {
	copyDir := t.TempDir()
	e := Exports{Slot: 1, Vars: []Var{
		{"MWS_SLOT", "1"},
		{"A", "has $HOME"},
		{"B", "it's"},
		{"C", ""},
	}}
	if err := WriteLease(copyDir, e); err != nil {
		t.Fatalf("WriteLease: %v", err)
	}
	body, err := os.ReadFile(filepath.Join(copyDir, LeaseFile))
	if err != nil {
		t.Fatal(err)
	}
	for _, line := range []string{"A='has $HOME'\n", `B="it's"` + "\n", "C=\n"} {
		if !strings.Contains(string(body), line) {
			t.Errorf("lease lacks %q:\n%s", line, body)
		}
	}
}

func TestWriteLeaseRefusesDefaultSlot(t *testing.T) {
	copyDir := t.TempDir()
	err := WriteLease(copyDir, NewExports(loadConfig(t, shopConfig), "/m", "main", 0))
	if err == nil {
		t.Fatal("WriteLease at slot 0 succeeded; slot 0 is never leased")
	}
	if _, statErr := os.Stat(filepath.Join(copyDir, LeaseFile)); !errors.Is(statErr, os.ErrNotExist) {
		t.Fatalf("lease written despite error: %v", statErr)
	}
}

func TestReadSlotRejectsMalformedLease(t *testing.T) {
	for name, body := range map[string]string{
		"no slot":    "MWS_COPY=x\n",
		"not number": "MWS_SLOT=abc\n",
		"zero":       "MWS_SLOT=0\n",
		"negative":   "MWS_SLOT=-2\n",
	} {
		t.Run(name, func(t *testing.T) {
			copyDir := t.TempDir()
			if err := os.WriteFile(filepath.Join(copyDir, LeaseFile), []byte(body), 0o644); err != nil {
				t.Fatal(err)
			}
			_, err := ReadSlot(copyDir)
			var leaseErr *LeaseError
			if !errors.As(err, &leaseErr) {
				t.Fatalf("ReadSlot error = %v, want *LeaseError", err)
			}
			if leaseErr.Path != filepath.Join(copyDir, LeaseFile) {
				t.Fatalf("LeaseError.Path = %q", leaseErr.Path)
			}
		})
	}
}

func TestRemoveLease(t *testing.T) {
	copyDir := t.TempDir()
	if err := WriteLease(copyDir, Exports{Slot: 2, Vars: []Var{{"MWS_SLOT", "2"}}}); err != nil {
		t.Fatal(err)
	}
	if err := RemoveLease(copyDir); err != nil {
		t.Fatalf("RemoveLease: %v", err)
	}
	if slot, err := ReadSlot(copyDir); err != nil || slot != 0 {
		t.Fatalf("ReadSlot after remove = %d, %v; want 0, nil", slot, err)
	}
	if err := RemoveLease(copyDir); err != nil {
		t.Fatalf("RemoveLease on a copy without a lease: %v", err)
	}
}
